# checker spec for 1430 (see lib/engine.sh)
SCRIPT_NAME=datecheck.sh
SEEDS=3
COMPARE="stdout exit errmsg"
input() {
  local i
  for ((i = 0; i < $(randr 8 14); i++)); do
    pick "$(randr 1890 2110)-$(printf %02d "$(randr 0 13)")-$(printf %02d "$(randr 0 32)")" \
         "$(randr 1995 2030)-$(printf %02d "$(randr 1 12)")-$(printf %02d "$(randr 28 31)")" \
         "$(pick 1900 2000 2004 2023 2024 2096 2100)-02-$(pick 28 29 30)" \
         "2024-2-01" "24-01-01" "2024/01/01" "2024-01-01x" "" "2024-08-09" "2023-09-31"
  done
}
ARGS=('-' '2024-02-29 2023-02-29 2000-02-29 1900-02-29 2096-02-29' '2024-04-31 2024-06-30 2024-08-09 2024-09-31 2024-12-31 2024-13-01 2024-00-10 2024-11-00' '1899-12-31 1900-01-01 2100-01-01 2099-12-31' '"2024-01-01 " x - 2024-1-1 ""' '' '- -' '2025-08-31')
